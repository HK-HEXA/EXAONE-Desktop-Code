'use strict';
// EXAONE Code(터미널 명령 `exaone`) 설치 · 제거 — 데스크톱 앱의 "설치" 버튼이 쓴다.
//
// 하는 일
//   1. 실행 묶음(런처)을 사용자 폴더에 만든다.
//        Windows      %LOCALAPPDATA%\EXAONE\bin\exaone.cmd (+ Git Bash 용 exaone)
//        macOS·Linux  ~/.local/bin/exaone
//      런처는 이 앱 안의 cli/exaone-code.js 를 실행한다. 실행에 쓸 Node 는 다음 순서로 고른다.
//        ① 앱에 함께 들어 있는 Node (배포판: resources/node/node.exe)
//        ② PC 에 설치된 Node (22.12 이상)
//        ③ 앱 자신 (Electron 을 Node 처럼 실행: ELECTRON_RUN_AS_NODE=1)
//   2. 그 폴더를 사용자 PATH 에 넣는다 (Windows: 사용자 환경 변수, 그 밖: 셸 설정 파일).
// 새로 여는 터미널부터 어디서나 `exaone` 을 쓸 수 있다. 관리자 권한은 필요 없다.

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');

const WIN = process.platform === 'win32';
const NAMES = ['exaone', 'exaone-code'];
const MIN_NODE = [22, 12];
const MARK = 'EXAONE Code launcher';

function binDir(env = process.env) {
  if (env.EXAONE_BIN_DIR) return env.EXAONE_BIN_DIR; // 시험용
  if (WIN) return path.join(env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local'), 'EXAONE', 'bin');
  return path.join(os.homedir(), '.local', 'bin');
}

function nodeVersionOk(v) {
  const m = /^v?(\d+)\.(\d+)/.exec(String(v).trim());
  if (!m) return false;
  const a = Number(m[1]), b = Number(m[2]);
  return a > MIN_NODE[0] || (a === MIN_NODE[0] && b >= MIN_NODE[1]);
}

/** PC 에 설치된 Node 가 쓸 만하면 그 버전을, 아니면 null. (ELECTRON_RUN_AS_NODE 가 켜진 환경에서 불려도 헷갈리지 않게 그 변수는 뺀다) */
function systemNode() {
  try {
    const env = { ...process.env };
    delete env.ELECTRON_RUN_AS_NODE;
    const out = execFileSync(WIN ? 'node.exe' : 'node', ['-v'], { encoding: 'utf8', timeout: 5000, windowsHide: true, env, stdio: ['ignore', 'pipe', 'ignore'] });
    return nodeVersionOk(out) ? out.trim() : null;
  } catch { return null; }
}

/**
 * 런처가 쓸 실행 환경을 고른다.
 * @param {{ appDir: string, execPath: string, resourcesPath?: string }} ctx
 * @returns {{ kind: 'bundled'|'system'|'electron', node: string, label: string, script: string }}
 */
function pickRuntime(ctx) {
  const script = path.join(ctx.appDir, 'cli', 'exaone-code.js');
  const bundled = ctx.resourcesPath ? path.join(ctx.resourcesPath, 'node', WIN ? 'node.exe' : 'node') : '';
  if (bundled && fs.existsSync(bundled)) return { kind: 'bundled', node: bundled, label: '앱에 포함된 Node', script };
  const sys = ctx.noSystemNode ? null : systemNode();
  if (sys) return { kind: 'system', node: 'node', label: `PC 에 설치된 Node ${sys}`, script };
  return { kind: 'electron', node: ctx.execPath, label: '앱 자체 실행 환경', script };
}

// ---------- 런처 내용 ----------
/** Windows 배치 파일 안에서 경로를 환경 변수로 줄여 쓴다 (사용자 이름에 한글이 있어도 파일 인코딩 문제가 없게). */
function winVarPath(p, env = process.env) {
  const esc = (t) => t.replace(/%/g, '%%'); // 배치 파일에서 % 는 두 번 써야 글자 그대로다
  for (const name of ['LOCALAPPDATA', 'APPDATA', 'USERPROFILE', 'ProgramFiles']) {
    const v = env[name];
    if (v && p.toLowerCase().startsWith(v.toLowerCase() + '\\')) return `%${name}%` + esc(p.slice(v.length));
  }
  return esc(p);
}

function cmdLauncher(rt, env) {
  const q = (p) => `"${winVarPath(p, env)}"`;
  return [
    '@echo off',
    `rem ${MARK} - generated by EXAONE Desktop. Reinstall from the app to update.`,
    'setlocal',
    rt.kind === 'electron' ? 'set ELECTRON_RUN_AS_NODE=1' : null,
    `${rt.kind === 'system' ? 'node' : q(rt.node)} ${q(rt.script)} %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].filter((l) => l != null).join('\r\n');
}

function shLauncher(rt) {
  const q = (p) => "'" + String(WIN ? p.replace(/\\/g, '/') : p).replace(/'/g, "'\\''") + "'";
  return [
    '#!/bin/sh',
    `# ${MARK} - generated by EXAONE Desktop. Reinstall from the app to update.`,
    `${rt.kind === 'electron' ? 'ELECTRON_RUN_AS_NODE=1 ' : ''}exec ${rt.kind === 'system' ? 'node' : q(rt.node)} ${q(rt.script)} "$@"`,
    '',
  ].join('\n');
}

/** 배치 파일은 콘솔의 코드 페이지로 읽힌다. 경로에 한글 등이 남아 있으면 그 코드 페이지로 저장한다 (PowerShell 사용). */
function writeCmd(file, content) {
  // eslint-disable-next-line no-control-regex
  if (/^[\x00-\x7f]*$/.test(content)) { fs.writeFileSync(file, content, 'latin1'); return; }
  const ps = `[IO.File]::WriteAllText(${psStr(file)}, ${psStr(content)}, [Text.Encoding]::GetEncoding([Globalization.CultureInfo]::CurrentCulture.TextInfo.OEMCodePage))`;
  runPs(ps);
}

const psStr = (s) => "'" + String(s).replace(/'/g, "''") + "'";
function runPs(script) {
  const r = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-EncodedCommand', Buffer.from(script, 'utf16le').toString('base64')],
    { encoding: 'utf8', timeout: 20000, windowsHide: true });
  if (r.error) throw r.error;
  if (r.status !== 0) throw new Error((r.stderr || r.stdout || 'PowerShell 실행 실패').trim().split('\n')[0]);
  return (r.stdout || '').trim();
}

/** dir 에 런처 파일들을 만든다. 돌려주는 값: 만든 파일 목록. */
function writeLaunchers(dir, rt, env = process.env) {
  fs.mkdirSync(dir, { recursive: true });
  const made = [];
  for (const name of NAMES) {
    if (WIN) {
      const f = path.join(dir, name + '.cmd');
      writeCmd(f, cmdLauncher(rt, env));
      made.push(f);
    }
    const f = path.join(dir, name); // Windows 에서는 Git Bash · WSL 이 아닌 MSYS 셸용
    fs.writeFileSync(f, shLauncher(rt), { encoding: 'utf8', mode: 0o755 });
    try { fs.chmodSync(f, 0o755); } catch { /* Windows */ }
    made.push(f);
  }
  return made;
}

const mainLauncher = (dir) => path.join(dir, WIN ? 'exaone.cmd' : 'exaone');

/** 그 파일이 우리가 만든 런처인지 (다른 프로그램의 exaone 을 지우지 않기 위해). */
function isOurs(file) {
  try { return fs.readFileSync(file, 'latin1').slice(0, 400).includes(MARK); } catch { return false; }
}

// ---------- PATH ----------
const samePath = (a, b) => path.resolve(a).replace(/[\\/]+$/, '').toLowerCase() === path.resolve(b).replace(/[\\/]+$/, '').toLowerCase();

/** Windows 사용자 PATH (레지스트리 HKCU\Environment) 를 읽는다. */
function winUserPath() {
  try {
    const out = execFileSync('reg.exe', ['query', 'HKCU\\Environment', '/v', 'Path'], { encoding: 'utf8', timeout: 8000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] });
    const m = /^\s*Path\s+REG_(?:EXPAND_)?SZ\s+(.*)$/mi.exec(out);
    return m ? m[1].trim() : '';
  } catch { return ''; }
}

/** Windows: 사용자 PATH 에 dir 을 넣거나(add) 뺀다. 값의 종류(REG_EXPAND_SZ)와 %변수% 표기를 그대로 두고, 바뀐 것을 열려 있는 프로그램들에 알린다. */
function winSetPath(dir, add) {
  const ps = [
    `$d = ${psStr(dir)}`,
    "$k = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)",
    "$p = [string]$k.GetValue('Path', '', 'DoNotExpandEnvironmentNames')",
    "$kind = 'ExpandString'; if ($p) { $kind = $k.GetValueKind('Path') }",
    "$parts = @($p.Split(';') | Where-Object { $_ -and ([Environment]::ExpandEnvironmentVariables($_).TrimEnd('\\') -ne $d.TrimEnd('\\')) })",
    add ? '$parts += $d' : '',
    "$new = ($parts -join ';')",
    "if ($new -ne $p) { $k.SetValue('Path', $new, $kind) }",
    '$k.Close()',
    // 환경 변수가 바뀌었음을 알린다 (새로 여는 터미널이 바로 새 PATH 를 받도록).
    "[Environment]::SetEnvironmentVariable('EXAONE_PATH_REFRESH', '1', 'User'); [Environment]::SetEnvironmentVariable('EXAONE_PATH_REFRESH', $null, 'User')",
  ].filter(Boolean).join('\n');
  runPs(ps);
}

/** macOS·Linux: 쓰는 셸의 설정 파일. */
function shellRc(env = process.env) {
  const sh = path.basename(env.SHELL || '');
  const home = os.homedir();
  if (sh === 'zsh') return path.join(home, '.zshrc');
  if (sh === 'bash') return path.join(home, process.platform === 'darwin' ? '.bash_profile' : '.bashrc');
  if (sh === 'fish') return null;
  return path.join(home, '.profile');
}
const RC_MARK = '# EXAONE Code (exaone)';
function posixSetPath(dir, add, env = process.env) {
  const rc = shellRc(env);
  if (!rc) return { rc: null };
  let text = '';
  try { text = fs.readFileSync(rc, 'utf8'); } catch { /* 새로 만든다 */ }
  const block = new RegExp('\\n?' + RC_MARK.replace(/[()]/g, '\\$&') + '\\n[^\\n]*\\n?', 'g');
  const stripped = text.replace(block, '\n').replace(/\n{3,}$/, '\n');
  const line = `${RC_MARK}\nexport PATH="${dir.startsWith(os.homedir()) ? '$HOME' + dir.slice(os.homedir().length) : dir}:$PATH"\n`;
  const next = add ? (stripped && !stripped.endsWith('\n') ? stripped + '\n' : stripped) + '\n' + line : stripped;
  if (next !== text) fs.writeFileSync(rc, next, 'utf8');
  return { rc };
}

function inPath(dir, env = process.env) {
  const list = WIN ? winUserPath().split(';').map((x) => x.replace(/%([^%]+)%/g, (_m, n) => env[n] || _m)) : (env.PATH || '').split(':');
  return list.filter(Boolean).some((x) => samePath(x, dir));
}

// ---------- 상태 · 설치 · 제거 ----------
/**
 * @returns {{ installed: boolean, dir: string, launcher: string, inPath: boolean, current: boolean, runtime: string, runtimeKind: string, other: string }}
 *   current: 런처가 지금 이 앱(위치·실행 환경)을 가리키는지. other: 우리가 만들지 않은 다른 exaone 명령의 위치(예: npm link).
 */
function status(ctx, env = process.env) {
  const dir = binDir(env);
  const launcher = mainLauncher(dir);
  const installed = fs.existsSync(launcher) && isOurs(launcher);
  const rt = pickRuntime(ctx);
  let current = false;
  if (installed) {
    // 한글 경로는 저장할 때의 인코딩이 달라질 수 있어 ASCII 부분만 견준다.
    // eslint-disable-next-line no-control-regex
    const ascii = (t) => t.replace(/[^\x00-\x7f]/g, '');
    try { current = ascii(fs.readFileSync(launcher, 'latin1')) === ascii(WIN ? cmdLauncher(rt, env) : shLauncher(rt)); } catch { /* 다시 설치하면 된다 */ }
  }
  let other = '';
  if (!installed) {
    try {
      const out = execFileSync(WIN ? 'where.exe' : 'which', ['exaone'], { encoding: 'utf8', timeout: 5000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] });
      other = (out.split(/\r?\n/).find((l) => l.trim() && !samePath(path.dirname(l.trim()), dir)) || '').trim();
    } catch { /* 없음 */ }
  }
  return { installed, dir, launcher, inPath: installed && inPath(dir, env), current, runtime: rt.label, runtimeKind: rt.kind, other };
}

function install(ctx, env = process.env) {
  const dir = binDir(env);
  const rt = pickRuntime(ctx);
  if (!fs.existsSync(rt.script)) throw new Error('EXAONE Code 파일을 찾을 수 없습니다: ' + rt.script);
  writeLaunchers(dir, rt, env);
  let pathNote = '';
  try {
    if (WIN) winSetPath(dir, true);
    else if (!inPath(dir, env)) { const r = posixSetPath(dir, true, env); pathNote = r.rc ? `${r.rc} 에 PATH 를 추가했습니다` : `PATH 에 ${dir} 를 직접 추가해 주세요`; }
  } catch (e) {
    return { ...status(ctx, env), pathError: 'PATH 등록 실패: ' + String(e && e.message || e) };
  }
  return { ...status(ctx, env), pathNote };
}

function uninstall(ctx, env = process.env) {
  const dir = binDir(env);
  for (const name of NAMES) for (const f of [path.join(dir, name), path.join(dir, name + '.cmd')]) {
    if (isOurs(f)) { try { fs.unlinkSync(f); } catch { /* 이미 없음 */ } }
  }
  try {
    if (WIN) { winSetPath(dir, false); try { fs.rmdirSync(dir); } catch { /* 다른 파일이 있으면 둔다 */ } }
    else posixSetPath(dir, false, env);
  } catch { /* PATH 정리는 실패해도 명령은 이미 지워졌다 */ }
  return status(ctx, env);
}

/** 설치돼 있는데 앱 위치나 실행 환경이 바뀌었으면(업데이트 · 폴더 이동) 런처를 새로 쓴다. 앱을 시작할 때 부른다. */
function refresh(ctx, env = process.env) {
  const st = status(ctx, env);
  if (!st.installed || st.current) return st;
  try { writeLaunchers(st.dir, pickRuntime(ctx), env); } catch { return st; }
  return status(ctx, env);
}

module.exports = { binDir, pickRuntime, writeLaunchers, mainLauncher, cmdLauncher, shLauncher, winVarPath, status, install, uninstall, refresh, nodeVersionOk };
